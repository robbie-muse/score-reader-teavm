#!/usr/bin/env python3
"""Phase §19: generate the pre-rendered Bravura symbol metrics.

Reads phase-font/symbol-metrics.json (desktop dump with the real Bravura
font) and emits two generated classes — do not edit by hand:

1. ../../teavm/shims/src/java/awt/font/BravuraMetrics.java
   Per-codepoint unit metrics (advance and bounds, per point size) for the
   157 Bravura code points the pipeline uses. The shim TextLayout consults
   this table: when the font name is "Bravura" and every code point of the
   text is known, getBounds()/getAdvance() compose the real Bravura
   geometry (verified exact on desktop: composition of multi-code strings
   from singles gives maxBoundsErr = maxAdvErr = 0.0 on 22 test strings).
   Unit values are taken from the reference size 84; linearity across
   40/84/168 is max 5.0e-4 per unit (<=0.09 px at size 168), so the
   rinted integer bounds Audiveris uses are stable.
   Other fonts (and unknown code points) fall back to the stub values.

2. ../../teavm/entry/src/teavm/PreRenderedSymbolMetrics.java
   Per-shape centroidOffset ratios (mass centre of the rendered symbol
   image, relative to area centre) for the 225 Bravura shapes, used by
   the patched ShapeSymbol.computeCentroidOffset (ROUND 15). The ratios
   are the exact values Audiveris computes from the STANDARD_INTERLINE
   image (size 80): a manual mass-centre computation from buildImage at
   size 80 reproduces the reflected centroidOffset with error 0.0000
   for every shape, so the table is exact, not approximate. (Ratios at
   other sizes differ for thin glyphs — e.g. STEM 0.177 at 168 — but no
   code path recomputes the centroid at another size: computeImage
   hard-codes STANDARD_INTERLINE, except tiny/decorated variants, which
   the patch leaves on the original path.)

Regenerate with: python3 gen_symbol_metrics.py   (run from phase-font/)
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "symbol-metrics.json")
SHIM_OUT = os.path.abspath(os.path.join(
    HERE, "..", "..", "teavm", "shims", "src", "java", "awt", "font",
    "BravuraMetrics.java"))
ENTRY_OUT = os.path.abspath(os.path.join(
    HERE, "..", "..", "teavm", "entry", "src", "teavm",
    "PreRenderedSymbolMetrics.java"))

d = json.load(open(SRC))
cps = d["codepoints"]          # str(cp) -> {"unit": {adv,x,y,w,h}, ...}
shapes = d["shapes"]           # name -> {"centroid": [ox, oy], ...}


def fmt(v):
    if float(v).is_integer():
        return f"{int(v)}.0"
    return repr(float(v))


# ---------------------------------------------------------------- shim table
cp_list = sorted(int(cp) for cp in cps)
lines = []
A = lines.append
A("package java.awt.font;")
A("")
A("/**")
A(" * Pre-rendered Bravura glyph metrics (per code point, per point size),")
A(" * dumped on desktop Java with the real Bravura font (see")
A(" * teavm-fork/phase-font/SymbolMetricsDump.java + symbol-metrics.json).")
A(" * Generated by phase-font/gen_symbol_metrics.py — do not edit by hand.")
A(" *")
A(" * The shim TextLayout consults this table when the font name is")
A(" * \"Bravura\": getBounds()/getAdvance() compose the real Bravura")
A(" * geometry from per-codepoint unit metrics (advance and bounds,")
A(" * divided by point size). Multi-code strings compose exactly")
A(" * (desktop verification: 22 multi-code strings, maxBoundsErr =")
A(" * maxAdvErr = 0.0). Other fonts, and code points not in this table,")
A(" * fall back to the stub TextLayout values.")
A(" *")
A(" * Unit values are from the reference size 84; linearity across sizes")
A(" * 40/84/168 is max 5.0e-4 per unit (<= 0.09 px at size 168).")
A(" */")
A("public class BravuraMetrics")
A("{")
A("    /** Code points, sorted ascending. */")
A("    private static final int[] CPS = {")
for i in range(0, len(cp_list), 12):
    A("            " + ", ".join(str(c) for c in cp_list[i:i + 12]) + ",")
A("    };")
for name, key in (("ADV", "adv"), ("X", "x"), ("Y", "y"), ("W", "w"), ("H", "h")):
    A("")
    A(f"    /** Unit {key} per code point (per point size), parallel to CPS. */")
    A(f"    private static final double[] {name} = {{")
    vals = [cps[str(cp)]["unit"][key] for cp in cp_list]
    for i in range(0, len(vals), 6):
        A("            " + ", ".join(fmt(v) for v in vals[i:i + 6]) + ",")
    A("    };")
A("")
A("    /**")
A("     * Report the unit metrics for a code point, or null when unknown.")
A("     *")
A("     * @param codePoint the Unicode code point")
A("     * @return {advance, x, y, width, height} per point size, or null")
A("     */")
A("    public static double[] get (int codePoint)")
A("    {")
A("        int lo = 0, hi = CPS.length - 1;")
A("        while (lo <= hi) {")
A("            int mid = (lo + hi) >>> 1;")
A("            int c = CPS[mid];")
A("            if (c == codePoint) {")
A("                return new double[] { ADV[mid], X[mid], Y[mid], W[mid], H[mid] };")
A("            } else if (c < codePoint) {")
A("                lo = mid + 1;")
A("            } else {")
A("                hi = mid - 1;")
A("            }")
A("        }")
A("        return null;")
A("    }")
A("}")
open(SHIM_OUT, "w").write("\n".join(lines) + "\n")

# ------------------------------------------------------------- centroid table
names = sorted(n for n, v in shapes.items() if v.get("centroid") is not None)
lines = []
A = lines.append
A("package teavm;")
A("")
A("/**")
A(" * Pre-rendered Bravura symbol centroid ratios, dumped on desktop Java")
A(" * with the real Bravura font (see teavm-fork/phase-font/")
A(" * SymbolMetricsDump.java + symbol-metrics.json). Generated by")
A(" * phase-font/gen_symbol_metrics.py — do not edit by hand.")
A(" *")
A(" * For each shape, the centroidOffset ratios (mass centre of the")
A(" * rendered symbol image, relative to area centre) that Audiveris")
A(" * computes from the STANDARD_INTERLINE image (size 80). The patched")
A(" * ShapeSymbol.computeCentroidOffset (ROUND 15) returns these instead")
A(" * of rendering a (blank, under the stub font) image and dividing 0/0.")
A(" * The table is exact: a manual mass-centre computation from")
A(" * buildImage at size 80 reproduces the stored ratios with error")
A(" * 0.0000 for every shape. Only Bravura is covered; other families")
A(" * return null and fall back to the original image computation.")
A(" */")
A("public class PreRenderedSymbolMetrics")
A("{")
A("    /** Shape names, sorted ascending. */")
A("    private static final String[] SHAPES = {")
for i in range(0, len(names), 6):
    A("            " + ", ".join('"' + n + '"' for n in names[i:i + 6]) + ",")
A("    };")
for arr, idx in (("OX", 0), ("OY", 1)):
    A("")
    A(f"    /** Centroid offset {'x' if idx == 0 else 'y'} ratios, parallel to SHAPES. */")
    A(f"    private static final double[] {arr} = {{")
    vals = [shapes[n]["centroid"][idx] for n in names]
    for i in range(0, len(vals), 6):
        A("            " + ", ".join(fmt(v) for v in vals[i:i + 6]) + ",")
    A("    };")
A("")
A("    /**")
A("     * Report the centroid offset ratios for a shape, or null when")
A("     * unknown (shape not pre-rendered, or a non-Bravura family).")
A("     *")
A("     * @param shapeName  the Shape enum name")
A("     * @param familyName the MusicFamily enum name")
A("     * @return {offsetX, offsetY} ratios, or null")
A("     */")
A("    public static double[] centroidOffset (String shapeName,")
A("                                          String familyName)")
A("    {")
A('        if (!"Bravura".equals(familyName)) {')
A("            return null;")
A("        }")
A("        int idx = java.util.Arrays.binarySearch(SHAPES, shapeName);")
A("        if (idx < 0) {")
A("            return null;")
A("        }")
A("        return new double[] { OX[idx], OY[idx] };")
A("    }")
A("}")
open(ENTRY_OUT, "w").write("\n".join(lines) + "\n")

print(f"codepoints={len(cp_list)} shapes={len(names)}")
print(f"wrote {SHIM_OUT}")
print(f"wrote {ENTRY_OUT}")
