#!/usr/bin/env python3
"""Phase B: generate teavm/PreRenderedTemplates.java from templates.json.

Reads the desktop template dump (native Audiveris + real Bravura) and emits
a Java class holding complete pre-rendered templates (width, height, slim
bounds, anchors, keyPoints) for Bravura catalogs at desktop point sizes
64/72/80/92/108, plus the lookup that maps a TeaVM-requested point size to the
nearest pre-rendered desktop catalog.

Derivation of the mapping (see FORK_FIX.md §17, superseded in §19):
  * §17: the shim TextLayout returned advance = 0.5 * size, so
    BlackHeadSizer calibrated the catalog to TeaVM pointSize =
    2.0 * measuredHeadWidth, and desktop = requested * 1.694827
    (1 / (2*a), a = 0.2950 Bravura NOTEHEAD_BLACK advance ratio).
  * §19: the shim TextLayout now returns real Bravura bounds, so
    computePointSize calibrates to the DESKTOP point size directly —
    requested == desktop, factor 1.0. Hymn: requested 92 -> catalog 92,
    the desktop calibration for this sheet (black-head mean width
    27.2 px, music-font point-size 92 in the desktop .omr scale block).
  * The advance ratio a is still asserted constant across catalogs
    (it is the cross-check that the dump's layout widths are sane).

Regenerate with: python3 gen_prerendered.py   (run from phaseb/)
 * §36: catalogs 64 + 72 added — the multi-page cliff: BWV 227 calibrates
 * to 64 and Hallelujah p04/p05/p06/p08 to 70-71, all below the old window
 * floor 72 ({80,92,108} +- 8); 71 missed by ONE point. Coverage is now
 * [56..116] continuous (64+-8, 72+-8, 80+-8, 92+-8, 108+-8).
Output: ../../teavm/entry/src/teavm/PreRenderedTemplates.java
"""
import json, math, os, sys
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "templates.json")
OUT = os.path.abspath(os.path.join(HERE, "..", "..", "teavm", "entry", "src", "teavm", "PreRenderedTemplates.java"))
WANT = [64, 72, 80, 92, 108]
MAX_DIFF = 8.0

d = json.load(open(SRC))
cats = {c["pointSize"]: c for c in d["catalogs"]}
missing = [ps for ps in WANT if ps not in cats]
if missing:
    sys.exit(f"templates.json lacks catalogs: {missing}")

# Advance ratio a from every catalog (should be constant); §19: it is now
# only a sanity check — the requested point size IS the desktop point size.
ratios = [c["blackLayoutWidth"] / c["pointSize"] for c in cats.values()]
a = sum(ratios) / len(ratios)
assert max(ratios) - min(ratios) < 0.001, ratios
RATIO = 1.0

def fmt_num(v):
    # integral doubles print as e.g. 9.0; keep exact Java double literal
    if float(v).is_integer():
        return f"{int(v)}.0"
    return repr(float(v))

lines = []
A = lines.append
A("package teavm;")
A("")
A("import java.awt.Rectangle;")
A("import java.util.ArrayList;")
A("import java.util.HashSet;")
A("import java.util.List;")
A("import java.util.Set;")
A("")
A("import org.audiveris.omr.glyph.Shape;")
A("import org.audiveris.omr.image.Anchored.Anchor;")
A("import org.audiveris.omr.image.PixelDistance;")
A("import org.audiveris.omr.image.Template;")
A("import org.audiveris.omr.ui.symbol.MusicFamily;")
A("")
A("/**")
A(" * Pre-rendered note-head templates, built offline on desktop Java with the")
A(" * real Bravura font (see phaseb/TemplateDump.java + templates.json) and")
A(" * bundled as data so the TeaVM run never needs the stub music font to")
A(" * render glyphs. Generated by phaseb/gen_prerendered.py — do not edit by hand.")
A(" *")
A(" * A template is fully specified by width, height, slim bounds, anchors and")
A(" * its keyPoints list (x, y, d); the lookup returns a Template built from")
A(" * exactly those values, so it is identical to the one native Audiveris")
A(" * builds at the same desktop point size (verified by the phaseb round-trip")
A(" * test, which compares every field and every key point).")
A(" *")
A(" * Point-size mapping (§19, supersedes §17): the shim TextLayout now")
A(" * returns real Bravura bounds, so BlackHeadSizer calibrates the")
A(" * catalog to the desktop point size directly — requested == desktop")
A(" * (factor 1.0; the §17 factor 1.694827 applied only while the shim")
A(" * reported advance 0.5*size). The Bravura NOTEHEAD_BLACK advance")
A(" * ratio a = "
    f"{a:.4f} (measured, constant across catalogs) is still asserted")
A(" * by the generator as a sanity check. The nearest")
A(" * pre-rendered catalog is used when it is within "
    f"{MAX_DIFF:.0f} of that value; otherwise")
A(" * null is returned and the caller falls back to building the template")
A(" * from the stub font (the Phase A behaviour).")
A(" *")
A(f" * Generated {date.today().isoformat()} from templates.json "
    f"(catalogs {WANT}, Bravura).")
A(" */")
A("public class PreRenderedTemplates")
A("{")
A("    /** Desktop point size per unit of requested point size (§19: 1.0 — requested IS desktop). */")
A(f"    public static final double DESKTOP_PER_REQUESTED_POINT = {RATIO!r};")
A("")
A("    /** Desktop point sizes with pre-rendered catalogs. */")
A("    public static final int[] CATALOG_POINT_SIZES = {"
    + ", ".join(str(ps) for ps in WANT) + "};")
A("")
A(f"    /** Maximum |picked - exact| for a catalog to be used, else fall back. */")
A(f"    private static final double MAX_DIFF = {MAX_DIFF};")
A("")
A("    private static final Set<String> logged = new HashSet<>();")
A("")
A("    /**")
A("     * Report the pre-rendered template for the given shape, or null when")
A("     * no pre-rendered catalog covers the requested point size.")
A("     *")
A("     * @param shape               desired head shape")
A("     * @param family              music font family (only Bravura is pre-rendered)")
A("     * @param requestedPointSize  point size the TeaVM catalog was asked for")
A("     * @return the template, or null to fall back to stub-font building")
A("     */")
A("    public static Template getTemplate (Shape shape,")
A("                                       MusicFamily family,")
A("                                       int requestedPointSize)")
A("    {")
A("        if (family != MusicFamily.Bravura) {")
A("            return null;")
A("        }")
A("")
A("        double exact = requestedPointSize * DESKTOP_PER_REQUESTED_POINT;")
A("        int best = -1;")
A("        double bestDiff = Double.MAX_VALUE;")
A("")
A("        for (int ps : CATALOG_POINT_SIZES) {")
A("            double diff = Math.abs(ps - exact);")
A("")
A("            if (diff < bestDiff) {")
A("                bestDiff = diff;")
A("                best = ps;")
A("            }")
A("        }")
A("")
A("        if ((best < 0) || (bestDiff > MAX_DIFF)) {")
A("            return null;")
A("        }")
A("")
A("        String key = requestedPointSize + \"->\" + best;")
A("")
A("        if (logged.add(key)) {")
A("            System.out.println(")
A("                    \"PreRenderedTemplates: requested \" + requestedPointSize")
A("                            + \" maps to desktop catalog \" + best);")
A("        }")
A("")
A("        switch (best) {")
for ps in WANT:
    A(f"            case {ps}:")
    A(f"                return tpl{ps}(shape);")
A("            default:")
A("                return null;")
A("        }")
A("    }")
A("")

total_kp = 0
for ps in WANT:
    cat = cats[ps]
    A(f"    //-------------------------//")
    A(f"    // Catalog at desktop point size {ps}")
    A(f"    //-------------------------//")
    A("")
    # Key-point data lives in locals inside each builder method, NOT in
    # static fields: 61k ints of static initializers would blow the JVM
    # 64 KB <clinit> limit ("code too large"). Per-method initializers
    # stay well under it (largest shape: 2263 key points).
    for s in cat["shapes"]:
        total_kp += len(s["keyPoints"])
    # per-catalog dispatch + builders
    A(f"    private static Template tpl{ps} (Shape shape)")
    A("    {")
    A("        switch (shape) {")
    for s in cat["shapes"]:
        name = s["shape"]
        A(f"            case {name}:")
        A(f"                return build{ps}_{name}();")
    A("            default:")
    A("                return null;")
    A("        }")
    A("    }")
    A("")
    for s in cat["shapes"]:
        name = s["shape"]
        slim = s["slim"]
        A(f"    private static Template build{ps}_{name} ()")
        A("    {")
        flat = []
        for (x, y, dd) in s["keyPoints"]:
            flat.extend([x, y, int(dd)])
        A("        int[] d = {")
        for i in range(0, len(flat), 36):
            chunk = flat[i:i + 36]
            A("            " + ", ".join(str(v) for v in chunk) + ("," if i + 36 < len(flat) else ""))
        A("        };")
        A(f"        List<PixelDistance> kps = new ArrayList<>(d.length / 3);")
        A("")
        A("        for (int i = 0; i < d.length; i += 3) {")
        A("            kps.add(new PixelDistance(d[i], d[i + 1], d[i + 2]));")
        A("        }")
        A("")
        A(f"        Template t = new Template(Shape.{name}, MusicFamily.Bravura, {ps}, "
          f"{s['width']}, {s['height']}, kps,")
        A(f"                new Rectangle({slim[0]}, {slim[1]}, {slim[2]}, {slim[3]}));")
        A("")
        for aname, (ax, ay) in s["anchors"].items():
            A(f"        t.putOffset(Anchor.{aname}, {fmt_num(ax)}, {fmt_num(ay)});")
        A("")
        A("        return t;")
        A("    }")
        A("")

A("}")
A("")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes, {total_kp} keyPoints in catalogs {WANT}, RATIO={RATIO:.6f})")
